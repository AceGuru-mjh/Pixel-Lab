        val out = HashMap<Char, IntArray>(96)
        for (g in 0..94) {
            val cols = IntArray(8)
            for (row in 0..7) {
                val bits = ROWS[g * 8 + row]
                for (col in 0..7) {
                    if (bits and (0x80 ushr col) != 0) cols[col] = cols[col] or (1 shl row)
                }
            }
            out[(g + 32).toChar()] = cols
        }
        return out
    }

