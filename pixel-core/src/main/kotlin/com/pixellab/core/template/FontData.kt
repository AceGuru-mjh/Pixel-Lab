package com.pixellab.core.template

/**
 * Abstraction over the built-in bitmap fonts.
 *
 * Glyph encoding contract (shared by both fonts):
 * [glyph] returns an array of [glyphWidth] column bytes, column 0 leftmost.
 * Inside a column byte, bit `k` (value `1 shl k`) is row `k` where row 0 is
 * the TOP row; bits `0 .. glyphHeight - 1` are used.
 */
interface PixelFont {
    /** Glyph cell width in pixels (columns per glyph). */
    val glyphWidth: Int

    /** Glyph cell height in pixels (rows per glyph). */
    val glyphHeight: Int

    /**
     * Column-encoded glyph for [c] (ASCII 32..126 coverage), or null for
     * unsupported characters — callers usually fall back to a space glyph.
     */
    fun glyph(c: Char): IntArray?

    /** First supported character code. */
    val firstChar: Char get() = ' '

    /** Last supported character code. */
    val lastChar: Char get() = '~'

    /** True when [c] has a glyph. */
    fun hasGlyph(c: Char): Boolean = glyph(c) != null
}

